import assert from 'node:assert/strict';
import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { chromium } from 'playwright';

const base = process.argv[2] || 'http://127.0.0.1:5173';
const output = 'output/glass-studio';
await mkdir(output, { recursive: true });
const baseline = JSON.parse(await readFile('src/content/glass-frosted-original.json', 'utf8'));
const initial = await (await fetch(base + '/__glass/api/settings')).json();
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
page.on('pageerror', e => errors.push(e.message));
const post = async data => {
  const response = await fetch(base + '/__glass/api/settings', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(data) });
  return { status: response.status, data: await response.json() };
};
const report = { checks: [], errors };
let testPreset;
try {
  assert.deepEqual(initial.presets.find(p => p.id === 'frosted-original').profiles, baseline);
  const protectedResult = await post({ action: 'deletePreset', id: 'frosted-original' });
  assert.equal(protectedResult.status, 400);
  const crossOrigin = await fetch(base + '/__glass/api/settings', { method: 'POST', headers: { 'Content-Type': 'application/json', Origin: 'https://example.com' }, body: '{}' });
  assert.equal(crossOrigin.status, 403);
  const invalidProfiles = structuredClone(initial.profiles);
  invalidProfiles.control.blurPx = -1;
  assert.equal((await post({ action: 'saveDefault', profiles: invalidProfiles })).status, 400);
  assert.deepEqual((await (await fetch(base + '/__glass/api/settings')).json()).profiles, initial.profiles);
  report.checks.push('original-preset-preserved-and-protected', 'cross-origin-write-rejected');
  await page.goto(base + '/__glass/');
  await page.getByRole('heading', { name: 'Glass Studio' }).waitFor();
  const preview = page.frameLocator('iframe');
  await preview.locator('[data-glass-type="control"]').first().waitFor();
  const beforeNav = await preview.locator('[data-glass-type="navigation"]').evaluate(e => e.getAttribute('style'));
  await page.getByRole('spinbutton', { name: '背景模糊数值', exact: true }).fill('0.3');
  await page.waitForTimeout(180);
  const surfaces = await preview.locator('[data-glass-type="control"]').evaluateAll(elements => elements.map(e => getComputedStyle(e).getPropertyValue('--glass-blur').trim()));
  assert(surfaces.length > 3 && surfaces.every(v => v === '0.3px'));
  assert.equal(await preview.locator('[data-glass-type="navigation"]').evaluate(e => e.getAttribute('style')), beforeNav);
  await page.getByRole('spinbutton', { name: '折射位移数值', exact: true }).fill('31');
  await page.waitForTimeout(180);
  assert(await preview.locator('[data-glass-type="control"]').evaluateAll(elements => elements.every(e => e.querySelector('feDisplacementMap')?.getAttribute('scale') === '-31')));
  report.checks.push('all-matching-buttons-live-update', 'actual-displacement-filter-updates', 'navigation-unchanged-by-button-edits');
  const other = await browser.newPage();
  await other.goto(base + '/publications');
  await other.locator('[data-glass-type="control"]').first().waitFor();
  await other.waitForFunction(() => document.querySelector('[data-glass-type="control"]')?.style.getPropertyValue('--glass-blur') === '0.3px', null, { timeout: 3000 });
  await page.getByRole('spinbutton', { name: '背景模糊数值', exact: true }).fill('0.4');
  await other.waitForFunction(() => document.querySelector('[data-glass-type="control"]')?.style.getPropertyValue('--glass-blur') === '0.4px');
  await other.close();
  await page.getByLabel('预览页面', { exact: true }).selectOption('/#about');
  await preview.locator('[data-glass-type="social"]').first().waitFor();
  await page.getByLabel('预览页面', { exact: true }).selectOption('/publications');
  await preview.locator('[data-glass-type="control"]').first().waitFor();
  await preview.locator('[data-glass-type="control"]').first().evaluate(e => {
    if (e.style.getPropertyValue('--glass-blur') !== '0.4px') throw new Error('Unsaved preview lost on navigation');
  });
  report.checks.push('independent-frontend-tab-live-sync', 'unsaved-preview-survives-route-change', 'invalid-profile-rejected-without-write');
  await page.getByLabel('新预设名称', { exact: true }).fill('Studio automated test');
  await page.getByRole('button', { name: '保存并应用预设', exact: true }).click();
  await page.getByRole('status').filter({ hasText: '已保存到本地' }).waitFor();
  const saved = await (await fetch(base + '/__glass/api/settings')).json();
  testPreset = saved.presets.find(p => p.name === 'Studio automated test' && !initial.presets.some(old => old.id === p.id));
  assert(testPreset); assert.equal(saved.profiles.control.blurPx, .4);
  await page.reload();
  await page.getByRole('spinbutton', { name: '背景模糊数值', exact: true }).waitFor();
  assert.equal(await page.getByRole('spinbutton', { name: '背景模糊数值', exact: true }).inputValue(), '0.4');
  report.checks.push('preset-saved-to-disk', 'default-survives-full-reload');
  await page.getByLabel('复制当前材质到', { exact: true }).selectOption('social');
  await page.getByRole('button', { name: '复制材质到目标类型', exact: true }).click();
  await preview.locator('[data-glass-type="social"]').first().waitFor();
  await page.waitForTimeout(200);
  assert.equal(await page.getByLabel('组件类型', { exact: true }).inputValue(), 'social');
  // Changing a copied preset is a live update, not a one-off DOM overwrite.
  await page.getByRole('spinbutton', { name: '背景模糊数值', exact: true }).fill('0.5');
  await page.waitForTimeout(150);
  assert(await preview.locator('[data-glass-type="social"]').evaluateAll(elements => elements.length === 6 && elements.every(e => e.style.getPropertyValue('--glass-blur') === '0.5px')));
  report.checks.push('cross-type-material-copy', 'six-social-buttons-share-type');
  await page.getByRole('button', { name: '点选组件', exact: true }).click();
  await preview.locator('[data-glass-type="portrait"]').click();
  await page.waitForFunction(() => document.querySelector('select[aria-label="组件类型"]').value === 'portrait');
  report.checks.push('pick-real-frontend-component');
  await page.getByLabel('组件类型', { exact: true }).selectOption('selection');
  await page.getByRole('spinbutton', { name: '折射强度数值', exact: true }).fill('0.02');
  await page.waitForTimeout(500);
  const iframe = page.frames().find(f => f !== page.mainFrame());
  await iframe.waitForFunction(() => window.__liquidGLRenderer__?.lenses[0]?.options.refraction === 0.02);
  report.checks.push('navigation-shader-live-parameter-update');
  await page.getByLabel('组件类型', { exact: true }).selectOption('control');
  await page.getByLabel('预览页面', { exact: true }).selectOption('/publications');
  await page.getByLabel('预设', { exact: true }).selectOption('clear-controls');
  await page.getByRole('button', { name: '套用当前类型', exact: true }).click();
  await preview.locator('[data-glass-type="control"]').first().waitFor();
  await page.waitForTimeout(600);
  await page.screenshot({ path: `${output}/studio-desktop.png` });
  await page.getByRole('button', { name: '手机', exact: true }).click();
  await page.waitForTimeout(450);
  assert.equal(await iframe.evaluate(() => innerWidth), 390);
  await page.screenshot({ path: `${output}/studio-mobile-preview.png` });
  for (const width of [900, 640, 390]) {
    await page.setViewportSize({ width, height: 900 });
    await page.waitForTimeout(250);
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), `Studio overflows at ${width}`);
  }
  await page.screenshot({ path: `${output}/studio-narrow.png` });
  report.checks.push('actual-390px-iframe-viewport', 'studio-responsive-390-to-1440');
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: '导出', exact: true }).click();
  const download = await downloadPromise;
  const exportedPath = `${output}/exported-preset.json`;
  await download.saveAs(exportedPath);
  const exported = JSON.parse(await readFile(exportedPath, 'utf8'));
  assert.equal(exported.profiles.control.blurPx, initial.presets.find(p => p.id === 'clear-controls').profiles.control.blurPx);
  await page.getByRole('button', { name: '原始', exact: true }).click();
  await page.locator('input[type="file"]').setInputFiles(exportedPath);
  await page.getByRole('status').filter({ hasText: '已导入到实时预览' }).waitFor();
  assert.equal(Number(await page.getByRole('spinbutton', { name: '背景模糊数值', exact: true }).inputValue()), exported.profiles.control.blurPx);
  report.checks.push('preset-json-export-and-import');
  assert.deepEqual(errors, []);
  report.passed = true;
} catch (error) {
  report.failure = error.stack; process.exitCode = 1;
  await page.screenshot({ path: `${output}/failure.png` }).catch(() => {});
} finally {
  await post({ action: 'saveDefault', profiles: initial.profiles });
  const latest = await (await fetch(base + '/__glass/api/settings')).json();
  for (const p of latest.presets.filter(p => p.name === 'Studio automated test' && !initial.presets.some(old => old.id === p.id))) await post({ action: 'deletePreset', id: p.id });
  await browser.close();
  await writeFile(`${output}/checks.json`, JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report));
}
